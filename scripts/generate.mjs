#!/usr/bin/env node
// Generates the typed API clients for both CLIs from openapi.json (copied from
// platform/frontend/public/openapi.json, which the backend generates from its Go schemas).
//
//   node scripts/generate.mjs          write node/src/generated.ts and python/clickruntime_cli/generated.py
//   node scripts/generate.mjs --check  fail if either file is out of date (CI)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const spec = JSON.parse(readFileSync(join(root, "openapi.json"), "utf8"));
// Help for each command (clickruntime <command> --help), shared by both CLIs.
const help = JSON.parse(readFileSync(join(root, "help.json"), "utf8")).commands;

const ops = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    const params = op.parameters ?? [];
    ops.push({
      id: op.operationId,
      method: method.toUpperCase(),
      path,
      pathParams: params.filter((p) => p.in === "path").map((p) => p.name),
      queryParams: params.filter((p) => p.in === "query").map((p) => p.name),
      body: Boolean(op.requestBody),
      tool: op["x-mcp-tool"] ?? null,
      response: responseRef(op),
      summary: op.summary ?? "",
    });
  }
}
ops.sort((a, b) => a.id.localeCompare(b.id));

function responseRef(op) {
  for (const code of ["200", "201"]) {
    const ref = op.responses?.[code]?.content?.["application/json"]?.schema?.$ref;
    if (ref) return ref.split("/").pop();
  }
  return null;
}

// ---- TypeScript ----
function tsType(s) {
  if (!s || Object.keys(s).length === 0) return "unknown";
  if (s.$ref) return s.$ref.split("/").pop();
  if (s.oneOf) return s.oneOf.map(tsType).join(" | ");
  const types = Array.isArray(s.type) ? s.type : [s.type];
  return types
    .map((t) => {
      switch (t) {
        case "string":
          return s.enum ? s.enum.map((e) => JSON.stringify(e)).join(" | ") : "string";
        case "integer":
        case "number":
          return "number";
        case "boolean":
          return "boolean";
        case "null":
          return "null";
        case "array":
          return `Array<${tsType(s.items)}>`;
        case "object":
          if (s.properties) return "{ " + Object.entries(s.properties).map(([k, v]) => `${k}?: ${tsType(v)}`).join("; ") + " }";
          return s.additionalProperties && s.additionalProperties !== true ? `Record<string, ${tsType(s.additionalProperties)}>` : "Record<string, unknown>";
        default:
          return "unknown";
      }
    })
    .join(" | ");
}

let ts = `// Generated by scripts/generate.mjs from openapi.json (API ${spec.info.version}). Do not edit.\n\n`;
for (const [name, schema] of Object.entries(spec.components.schemas)) {
  const req = new Set(schema.required ?? []);
  ts += `export interface ${name} {\n`;
  for (const [k, v] of Object.entries(schema.properties ?? {})) {
    if (v.description) ts += `  /** ${v.description.replace(/\*\//g, "")} */\n`;
    ts += `  ${k}${req.has(k) ? "" : "?"}: ${tsType(v)};\n`;
  }
  ts += `}\n\n`;
}
ts += `export interface Operation {\n  method: "GET" | "POST" | "PATCH" | "DELETE";\n  path: string;\n  pathParams: readonly string[];\n  queryParams: readonly string[];\n  body: boolean;\n  tool: string | null;\n}\n\n`;
ts += `export const operations = {\n`;
for (const o of ops) {
  ts += `  /** ${o.summary.replace(/\*\//g, "")} */\n`;
  ts += `  ${o.id}: { method: "${o.method}", path: "${o.path}", pathParams: ${JSON.stringify(o.pathParams)}, queryParams: ${JSON.stringify(o.queryParams)}, body: ${o.body}, tool: ${JSON.stringify(o.tool)} },\n`;
}
ts += `} as const satisfies Record<string, Operation>;\n\nexport type OperationId = keyof typeof operations;\n\n`;
ts += `export interface Responses {\n`;
for (const o of ops) ts += `  ${o.id}: ${o.response ?? "unknown"};\n`;
ts += `}\n\nexport const API_VERSION = ${JSON.stringify(spec.info.version)};\n`;
ts += `\nexport interface HelpTopic {\n  usage: string;\n  summary: string;\n  details?: string[];\n  flags?: [string, string][];\n  output?: string;\n  exits?: string;\n  next?: string;\n}\n\n`;
ts += `/** From help.json: help for each command. */\nexport const HELP_TOPICS: Record<string, HelpTopic> = ${JSON.stringify(help, null, 2)};\n`;

// ---- Python ----
function pyType(s) {
  if (!s || Object.keys(s).length === 0) return "Any";
  if (s.$ref) return `"${s.$ref.split("/").pop()}"`;
  if (s.oneOf) return `Union[${s.oneOf.map(pyType).join(", ")}]`;
  const types = Array.isArray(s.type) ? s.type : [s.type];
  const out = types.map((t) => {
    switch (t) {
      case "string":
        return "str";
      case "integer":
        return "int";
      case "number":
        return "float";
      case "boolean":
        return "bool";
      case "null":
        return "None";
      case "array":
        return `List[${pyType(s.items)}]`;
      case "object":
        return "Dict[str, Any]";
      default:
        return "Any";
    }
  });
  return out.length === 1 ? out[0] : `Optional[${out.filter((t) => t !== "None").join(", ")}]`;
}

let py = `# Generated by scripts/generate.mjs from openapi.json (API ${spec.info.version}). Do not edit.\n`;
py += `from typing import Any, Dict, List, Optional, TypedDict, Union\n\n`;
py += `API_VERSION = ${JSON.stringify(spec.info.version)}\n\n`;
for (const [name, schema] of Object.entries(spec.components.schemas)) {
  py += `${name} = TypedDict("${name}", {\n`;
  for (const [k, v] of Object.entries(schema.properties ?? {})) py += `    "${k}": ${pyType(v)},\n`;
  py += `}, total=False)\n\n`;
}
py += `# operationId -> (method, path, path params, query params, has body, MCP tool)\n`;
py += `OPERATIONS: Dict[str, Dict[str, Any]] = {\n`;
for (const o of ops) {
  py += `    "${o.id}": {"method": "${o.method}", "path": "${o.path}", "path_params": ${JSON.stringify(o.pathParams)}, "query_params": ${JSON.stringify(o.queryParams)}, "body": ${o.body ? "True" : "False"}, "tool": ${o.tool ? JSON.stringify(o.tool) : "None"}},\n`;
}
py += `}\n`;
py += `\n# From help.json: help for each command.\nHELP_TOPICS: Dict[str, Dict[str, Any]] = ${JSON.stringify(help, null, 4)}\n`;

const targets = [
  [join(root, "node", "src", "generated.ts"), ts],
  [join(root, "python", "clickruntime_cli", "generated.py"), py],
];
if (process.argv.includes("--check")) {
  let stale = false;
  for (const [file, text] of targets) {
    let cur = "";
    try {
      cur = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
    } catch {}
    if (cur !== text) {
      console.error(`${file} is out of date; run node scripts/generate.mjs`);
      stale = true;
    }
  }
  process.exit(stale ? 1 : 0);
}
for (const [file, text] of targets) writeFileSync(file, text);
console.log(`generated ${ops.length} operations`);
